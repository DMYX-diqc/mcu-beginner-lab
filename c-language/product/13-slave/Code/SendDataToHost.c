/*********************************************************************************************************
* 函数名称: SendPackToHost
* 函数功能: 发送包到主机
* 输入参数: packSent
* 输出参数: void
* 返 回 值: void
* 创建日期: 2021年03月01日
* 注    意: 
*********************************************************************************************************/
static  void  SendPackToHost(StructPackType* pPackSent)
{
  u8  valid;
  i16 i = 0;

  valid = PackData(pPackSent);     //调用打包函数来打包数据

  if(1 == valid)
  {
    for(i = 0; i < 10; i++)
    {
      printf("%02x ", *((u8 *)pPackSent + i));
    }
  }
}

