/*********************************************************************************************************
* 函数名称: ProcHostCmd
* 函数功能: 处理主机发送来的命令 
* 输入参数: recData
* 输出参数: void
* 返 回 值: void
* 创建日期: 2021年03月01日
* 注    意: 
*********************************************************************************************************/
void ProcHostCmd(u8 recData)
{
  u8 ack;
  StructPackType pack;

  while(UnPackData(recData))
  {
    pack = GetUnPackRslt();              //获取解包结果
    switch(pack.packModuleId)
    {
      case MODULE_WAVE1:
        if(CMD_GEN_WAVE1 == pack.packSecondId)
        {
		    ack = OnGenWave1(pack.arrData);
            printf("GEN_WAVE1 ACK:\n"); 
            SendAckPack(MODULE_WAVE1, CMD_GEN_WAVE1, ack);     //发送响应包
            printf("\n"); 
            printf("------WAVE1------\n");
            //printf("ID1-%d\n",s_iTimerWave1Id);
		}
        break;
      case MODULE_WAVE2:
        if(CMD_GEN_WAVE2 == pack.packSecondId)
        {
		    ack = OnGenWave2(pack.arrData);
            printf("GEN_WAVE2 ACK:\n"); 
            SendAckPack(MODULE_WAVE2, CMD_GEN_WAVE2, ack);     //发送响应包
            printf("\n"); 
            printf("------WAVE2------\n");
        }
		break;
      default:
        timeKillEvent(s_iTimerWave1Id);
        timeKillEvent(s_iTimerWave2Id);        
        break;
    }
  }   
}