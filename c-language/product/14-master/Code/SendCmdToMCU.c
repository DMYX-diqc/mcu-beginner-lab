/*********************************************************************************************************
* 函数名称: SendPackToMCU
* 函数功能: 发送Pack到从机
* 输入参数: pPackSent-包类型结构体指针
* 输出参数: void
* 返 回 值: void
* 创建日期: 2021年03月01日
* 注    意: 
*********************************************************************************************************/
static  void  SendPackToMCU(StructPackType* pPackSent)
{
  u8  valid;
  i16 i = 0;

  valid = PackData(pPackSent);     //调用打包函数来打包数据

  if(1 == valid)
  {
    for(i = 0; i < 10; i++)
    {
      printf("%02x ", *((u8 *)pPackSent + i));    //将打包好的数据发送出去，这里使用printf进行模拟
    }
  }
}

