/*********************************************************************************************************
* 函数名称: SendGenWave1CmdToMCU
* 函数功能: 发送生成wave1命令到从机
* 输入参数: void
* 输出参数: void
* 返 回 值: void
* 创建日期: 2021年03月01日
* 注    意: 
*********************************************************************************************************/
void  SendGenWave1CmdToMCU(void)
{
  StructPackType  pt;

  pt.packModuleId = MODULE_WAVE1;
  pt.packSecondId = CMD_GEN_WAVE1;
  pt.arrData[0] = 0;
  pt.arrData[1] = 0;
  pt.arrData[2] = 0;
  pt.arrData[3] = 0;
  pt.arrData[4] = 0;
  pt.arrData[5] = 0;
  
  SendPackToMCU(&pt);      //调用打包函数来打包数据，并数据发送到从机
}

