/*********************************************************************************************************
* 函数名称: InitTick
* 函数功能: 初始化Tick模块
* 输入参数: void 
* 输出参数: void
* 返 回 值: void
* 创建日期: 2021年03月01日 
* 注    意: 
*********************************************************************************************************/
void  InitTick(void)
{
  s_iTickVal = 0;
}

/*********************************************************************************************************
* 函数名称: TickPer2Ms
* 函数功能: 每2ms执行一次
* 输入参数: void 
* 输出参数: void
* 返 回 值: void
* 创建日期: 2021年03月01日 
* 注    意: 
*********************************************************************************************************/
void  TickPer2Ms(void)
{
  static  short s_iCnt = 0;

  if(s_iCnt >= 499)
  {
    if(s_iTickVal >= 86399)
    {
      s_iTickVal = 0;
    }
    else
    {
      s_iTickVal++;
    }
    s_iCnt = 0;
  }
  else
  {
    s_iCnt++; 
  }
}

/*********************************************************************************************************
* 函数名称: SetTickVal
* 函数功能: 设置tick值
* 输入参数: tick 
* 输出参数: void
* 返 回 值: void
* 创建日期: 2021年03月01日 
* 注    意: 
*********************************************************************************************************/
void  SetTickVal(int tick)
{
  s_iTickVal = tick;
}

/*********************************************************************************************************
* 函数名称: GetTickVal
* 函数功能: 获取tick值
* 输入参数: void 
* 输出参数: void
* 返 回 值: tick值
* 创建日期: 2021年03月01日 
* 注    意: 
*********************************************************************************************************/
int   GetTickVal(void)
{
  return(s_iTickVal);  
}

