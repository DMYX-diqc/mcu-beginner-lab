/*********************************************************************************************************
* 函数名称: InitCalcTime
* 函数功能: 初始化CalcTime模块
* 输入参数: void 
* 输出参数: void
* 返 回 值: void
* 创建日期: 2021年03月01日
* 注    意: 
*********************************************************************************************************/
void  InitCalcTime(void)
{
  InitCalcHour();
  InitCalcMin();
  InitCalcSec();
}

/*********************************************************************************************************
* 函数名称: CalcTime
* 函数功能: 计算时间
* 输入参数: tick，即以秒为单位的计数值 
* 输出参数: void
* 返 回 值: hour、min或sec，具体是哪一个根据type来确定
* 创建日期: 2021年03月01日
* 注    意: 
*********************************************************************************************************/
short CalcTime(int tick, unsigned char type)
{
  short timeVal;

  switch(type)
  {
    case TIME_VAL_HOUR:
      timeVal = CalcHour(tick);    //通过调用CalcHour计算小时值
      break;
    case TIME_VAL_MIN:
      timeVal = CalcMin(tick);     //通过调用CalcMin计算分钟值
      break;
    case TIME_VAL_SEC:
      timeVal = CalcSec(tick);     //通过调用CalcSec计算秒值
      break;
    default:
      break;  
  }
  
  return(timeVal);
}

