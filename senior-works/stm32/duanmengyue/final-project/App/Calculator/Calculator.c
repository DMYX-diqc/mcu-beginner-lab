// ==========================计算器全局状态=============================//
char expr_buf[EXPR_MAX_LEN];  // 存储完整运算式，如"3+9"
uint8_t expr_len = 0;         // 当前表达式有效长度
float calc_result = 0.0f;          // 计算结果(可以是浮点数)
uint8_t flag_has_expr = 0;    // 1=存在有效表达式，0=无
uint8_t flag_calc_done = 0;   // 1=已按下KEY1计算完成
uint8_t calc_err = 0; // 1 = 出现除零错误，0 = 无错误
// ====================== 多运算符四则运算栈 ===========================//

// 数字栈（浮点栈）、运算符栈
float num_stack[STACK_MAX]; //操作数栈
char op_stack[STACK_MAX]; //运算符栈
uint8_t num_top = 0;      //数字栈的栈顶指针
uint8_t op_top = 0;       //运算符栈的栈顶指针

// =========================历史记录环形缓存==========================//
char hist_expr[HIST_REC_MAX][EXPR_MAX_LEN];
float hist_result[HIST_REC_MAX];
uint8_t hist_store_idx = 0;
uint8_t hist_valid_cnt = 0;

// ===========================OLED页面标记===========================//
uint8_t oled_page = 0;
