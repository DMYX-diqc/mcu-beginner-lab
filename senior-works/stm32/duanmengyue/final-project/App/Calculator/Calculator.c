static uint8_t GetOpPri(char op);
static void CalcOnce(void);

/*********************************************************************************************************
*                                              内部函数实现
*********************************************************************************************************/
/*********************************************************************************************************
* 函数名称：GetOpPri
* 函数功能：获取运算符优先级
*********************************************************************************************************/
static uint8_t GetOpPri(char op)
{
    if(op == '(') return 0;
    if(op == '+' || op == '-') return 1;
    if(op == '*' || op == '/') return 2;
    return 0;
}

/*********************************************************************************************************
* 函数名称：CalcOnce
* 函数功能：弹出两个数字和一个运算符，计算结果压回数字栈
*********************************************************************************************************/
static void CalcOnce(void)
{
    float b = num_stack[--num_top];
    float a = num_stack[--num_top];
    char op = op_stack[--op_top];
    float res = 0.0f;

    switch(op)
    {
        case '+': res = a + b; break;
        case '-': res = a - b; break;
        case '*': res = a * b; break;
        case '/'://取b的绝对值，1乘以10的-6次方 = 0.000001
            if(fabs(b) < 1e-6f)// 浮点数不能直接==0，极小值判定为0
            {
                printf("错误：除数不能为0！\r\n");
                calc_err = 1;
                return;
            }
            res = a / b; // 向0取整
            break;
        default:return;
    }
    num_stack[num_top++] = res;
}

